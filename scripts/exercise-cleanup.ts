// Exercise name cleanup helper (db/2026-11-17-exercise-cleanup.md). Reads files Anand exports from the SQL
// Editor and writes a CSV / SQL to check by hand. It never talks to the database itself.
//
//   npx tsc scripts/exercise-cleanup.ts --outDir /tmp/ec --module commonjs --target es2020 --skipLibCheck
//   node /tmp/ec/scripts/exercise-cleanup.js suggest unmatched.json exercises.json > exercise-cleanup.csv
//   node /tmp/ec/scripts/exercise-cleanup.js sql exercise-cleanup-approved.csv > exercise-aliases.sql
//
// suggest: one CSV line per gym and typed name with the findExercise suggestion (lib/exercises.ts, the same
//          rule the app uses: same key, alias, same words reordered, or a close spelling).
// sql:     from the approved CSV (rows with an empty suggested_exercise_id are skipped), one
//          update per row that appends the typed name, lower case, to that exercise's aliases if it isn't there
//          yet, plus the undo. Session data is never edited.

import { readFileSync } from 'fs'
import { findExercise, type Exercise } from '../lib/exercises'

type Unmatched = { company: string; company_id: string; typed_name: string; count: number }

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

// The SQL Editor's "copy cell" of a json_agg(...) result; null (no rows) reads as []
function readJson<T>(path: string): T[] {
  const text = readFileSync(path, 'utf8').trim()
  if (!text || text === 'null' || text === 'NULL') return []
  const v = JSON.parse(text)
  if (!Array.isArray(v)) throw new Error(`${path}: expected a JSON list (the json_agg cell)`)
  return v as T[]
}

const csvCell = (v: unknown) => {
  const s = v == null ? '' : String(v)
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}

// Small CSV reader (quoted cells, "" inside quotes, commas and new lines inside quotes)
function parseCsv(text: string): string[][] {
  const rows: string[][] = []
  let row: string[] = [], cell = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++ }
      else if (c === '"') quoted = false
      else cell += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(cell); cell = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(cell); cell = ''
      if (row.some(x => x !== '')) rows.push(row)
      row = []
    } else cell += c
  }
  row.push(cell)
  if (row.some(x => x !== '')) rows.push(row)
  return rows
}

const sqlText = (s: string) => `'${s.replace(/'/g, "''")}'`

function suggest(unmatchedPath: string, exercisesPath: string) {
  const unmatched = readJson<Unmatched>(unmatchedPath)
  const exercises = readJson<Exercise>(exercisesPath)
  const out = [['company', 'typed_name', 'count', 'suggested_exercise_id', 'suggested_name'].join(',')]
  let found = 0
  for (const u of unmatched) {
    // The gym's own exercises and the starter list, like the app sees them
    const list = exercises.filter(e => !e.company_id || e.company_id === u.company_id)
    const m = findExercise(u.typed_name, list)
    if (m) found++
    out.push([u.company, u.typed_name, u.count, m?.exercise.id ?? '', m?.exercise.name ?? ''].map(csvCell).join(','))
  }
  process.stdout.write(out.join('\n') + '\n')
  process.stderr.write(`${unmatched.length} names, ${found} with a suggestion\n`)
}

function sql(approvedPath: string) {
  const rows = parseCsv(readFileSync(approvedPath, 'utf8'))
  const head = rows.shift()?.map(h => h.trim().toLowerCase()) ?? []
  const col = (name: string) => {
    const i = head.indexOf(name)
    if (i < 0) throw new Error(`${approvedPath}: no "${name}" column`)
    return i
  }
  const [cTyped, cId, cName] = [col('typed_name'), col('suggested_exercise_id'), col('suggested_name')]
  const seen = new Set<string>()
  const apply: string[] = [], undo: string[] = []
  for (const r of rows) {
    const id = (r[cId] || '').trim()
    const alias = (r[cTyped] || '').trim().replace(/\s+/g, ' ').toLowerCase()
    if (!id || !alias) continue
    if (!UUID.test(id)) throw new Error(`Not an exercise id: "${id}" (typed name "${r[cTyped]}")`)
    const k = `${id}|${alias}`
    if (seen.has(k)) continue
    seen.add(k)
    const comment = `-- ${alias} → ${(r[cName] || '').trim()}`
    apply.push(comment, `update public.exercises set aliases = array_append(aliases, ${sqlText(alias)}) where id = ${sqlText(id)} and not (${sqlText(alias)} = any(aliases));`)
    undo.push(`-- update public.exercises set aliases = array_remove(aliases, ${sqlText(alias)}) where id = ${sqlText(id)};`)
  }
  process.stdout.write([
    `-- Exercise aliases from ${approvedPath} (${seen.size} aliases). Generated by scripts/exercise-cleanup.ts.`,
    '-- Adds each typed name, lower case, to the matched exercise\'s aliases. Session data is not edited.',
    'begin;', ...apply, 'commit;', '',
    '-- Undo (only if Anand asks): removes exactly these aliases again',
    '-- begin;', ...undo, '-- commit;', '',
  ].join('\n'))
}

const [mode, a, b] = process.argv.slice(2)
if (mode === 'suggest' && a && b) suggest(a, b)
else if (mode === 'sql' && a) sql(a)
else {
  process.stderr.write('Usage:\n  node exercise-cleanup.js suggest unmatched.json exercises.json > exercise-cleanup.csv\n  node exercise-cleanup.js sql exercise-cleanup-approved.csv > exercise-aliases.sql\n')
  process.exit(1)
}
